// Generates src/api/generated/schema.ts from src/api/generated/openapi.json (the backend's
// OpenAPI, dumped by backend/scripts/dump_openapi.py). `npm run gen:api` runs both steps;
// src/api/generated/schema.test.ts fails when the committed file is out of date.
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import openapiTS, { astToString, type OpenAPI3 } from 'openapi-typescript';

const HEADER = `// Generated by \`npm run gen:api\` from openapi.json (openapi-typescript). Do not edit.
// The app imports these types through src/api/contract, never directly.
`;

// Plain paths, not URLs: under jsdom (the tests) the global URL is not Node's.
const GENERATED = path.join(path.dirname(fileURLToPath(import.meta.url)), '../src/api/generated');
export const SCHEMA_JSON = path.join(GENERATED, 'openapi.json');
export const SCHEMA_TS = path.join(GENERATED, 'schema.ts');

/** The TypeScript of an OpenAPI document, exactly as committed. */
export async function generate(document: OpenAPI3): Promise<string> {
  return HEADER + astToString(await openapiTS(document));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const document = JSON.parse(await readFile(SCHEMA_JSON, 'utf8')) as OpenAPI3;
  await writeFile(SCHEMA_TS, await generate(document));
}
