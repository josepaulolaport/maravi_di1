-- Ledger: two tables again.
DROP TABLE ledger.entries;
CREATE TABLE ledger.trades (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    asset_id UUID NOT NULL REFERENCES asset.instruments(id) ON DELETE RESTRICT,
    trade_date DATE NOT NULL,
    trade_time TIME NOT NULL,          -- Sao Paulo local time; order (trade_date, trade_time, seq) (OQ-13)
    seq BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE NOT NULL,
    signed_quantity INTEGER NOT NULL,
    execution_pu NUMERIC NOT NULL,
    execution_rate NUMERIC NOT NULL,
    input_kind VARCHAR(8) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ,
    delete_reason TEXT,
    CONSTRAINT trades_qty_nonzero CHECK (signed_quantity <> 0),
    CONSTRAINT trades_pu_positive CHECK (execution_pu > 0),
    CONSTRAINT trades_rate_valid CHECK (execution_rate > -1),
    CONSTRAINT trades_input_kind CHECK (input_kind IN ('PU','RATE')),
    CONSTRAINT trades_delete_reason_tied CHECK (delete_reason IS NULL OR deleted_at IS NOT NULL)
);
CREATE INDEX trades_ordered_active_idx ON ledger.trades (trade_date, trade_time, seq) WHERE deleted_at IS NULL;
CREATE INDEX trades_asset_date_active_idx ON ledger.trades (asset_id, trade_date, seq) WHERE deleted_at IS NULL;

CREATE TABLE ledger.cash_movements (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    movement_date DATE NOT NULL,
    movement_type VARCHAR(16) NOT NULL,
    amount NUMERIC(20,2) NOT NULL,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ,
    delete_reason TEXT,
    CONSTRAINT cash_movements_type_check CHECK (movement_type IN ('DEPOSIT','WITHDRAWAL')),
    CONSTRAINT cash_movements_amount_positive CHECK (amount > 0),
    CONSTRAINT cash_movements_delete_reason_tied CHECK (delete_reason IS NULL OR deleted_at IS NOT NULL)
);
CREATE INDEX cash_movements_active_date_idx ON ledger.cash_movements (movement_date) WHERE deleted_at IS NULL;

