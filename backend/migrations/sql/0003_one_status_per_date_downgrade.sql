-- Processing: staging, the request's range bookkeeping, revisions and markers again.
CREATE TABLE portfolio.staged_positions (
    request_id UUID NOT NULL REFERENCES processing.requests(id) ON DELETE CASCADE,
    asset_id UUID NOT NULL REFERENCES asset.instruments(id) ON DELETE RESTRICT,
    position_date DATE NOT NULL,
    quantity INTEGER NOT NULL,
    PRIMARY KEY(request_id, asset_id, position_date)
);
CREATE TABLE portfolio.staged_position_metrics (
    request_id UUID NOT NULL,
    asset_id UUID NOT NULL,
    metric_date DATE NOT NULL,
    average_entry_pu NUMERIC,
    average_entry_rate NUMERIC,
    reference_price_id UUID,
    reference_pu NUMERIC,
    financial_total NUMERIC,
    position_pnl NUMERIC,
    trades_pnl NUMERIC,
    daily_pnl NUMERIC,
    valuation_status VARCHAR(16) NOT NULL CHECK (valuation_status IN ('COMPLETE','MISSING','NOT_REQUIRED')),
    pnl_status VARCHAR(16) NOT NULL CHECK (pnl_status IN ('COMPLETE','MISSING')),
    PRIMARY KEY(request_id, asset_id, metric_date),
    FOREIGN KEY(request_id, asset_id, metric_date) REFERENCES portfolio.staged_positions(request_id, asset_id, position_date) ON DELETE CASCADE,
    FOREIGN KEY(reference_price_id, asset_id, metric_date) REFERENCES prices.reference_prices(id, asset_id, reference_date) ON DELETE RESTRICT
);
CREATE TABLE portfolio.staged_portfolio_metrics (
    request_id UUID NOT NULL REFERENCES processing.requests(id) ON DELETE CASCADE,
    metric_date DATE NOT NULL,
    positions_market_value NUMERIC,
    aum NUMERIC,
    position_pnl NUMERIC,
    trades_pnl NUMERIC,
    daily_pnl NUMERIC,
    cumulative_pnl NUMERIC,
    valuation_status VARCHAR(16) NOT NULL CHECK (valuation_status IN ('COMPLETE','MISSING')),
    pnl_status VARCHAR(16) NOT NULL CHECK (pnl_status IN ('COMPLETE','MISSING')),
    PRIMARY KEY(request_id, metric_date)
);
CREATE TABLE portfolio.staged_cash_balances (
    request_id UUID NOT NULL REFERENCES processing.requests(id) ON DELETE CASCADE,
    balance_date DATE NOT NULL,
    cash_balance NUMERIC NOT NULL,
    trades_cash_flow NUMERIC NOT NULL,
    deposits NUMERIC NOT NULL,
    withdrawals NUMERIC NOT NULL,
    CONSTRAINT staged_cash_balances_movements_nonnegative CHECK (deposits >= 0 AND withdrawals >= 0),
    PRIMARY KEY(request_id, balance_date)
);

