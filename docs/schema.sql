-- Maravi DI1 Backoffice - target PostgreSQL 16+ schema
-- Architecture specification, not a previously executed migration.
-- All dates in the portfolio processing domain are calendar dates.
-- Precision: retain full NUMERIC arithmetic; perform intentional rounding in the domain.
BEGIN;
CREATE SCHEMA IF NOT EXISTS asset;
CREATE SCHEMA IF NOT EXISTS ledger;
CREATE SCHEMA IF NOT EXISTS prices;
CREATE SCHEMA IF NOT EXISTS portfolio;
CREATE SCHEMA IF NOT EXISTS processing;
CREATE SCHEMA IF NOT EXISTS platform;

-- ASSET: type -> class -> product -> instrument. Futures product specifications are shared.
CREATE TABLE asset.instrument_types (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(32) NOT NULL,
    name VARCHAR(100) NOT NULL,
    CONSTRAINT instrument_types_code_format CHECK (code ~ '^[A-Z][A-Z0-9_]*$')
);
CREATE UNIQUE INDEX instrument_types_code_uq ON asset.instrument_types (upper(code));

CREATE TABLE asset.asset_classes (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instrument_type_id SMALLINT NOT NULL REFERENCES asset.instrument_types(id) ON DELETE RESTRICT,
    code VARCHAR(64) NOT NULL,
    name VARCHAR(150) NOT NULL,
    CONSTRAINT asset_classes_code_format CHECK (code ~ '^[A-Z][A-Z0-9_]*$')
);
CREATE UNIQUE INDEX asset_classes_code_uq ON asset.asset_classes (upper(code));
CREATE INDEX asset_classes_instrument_type_idx ON asset.asset_classes (instrument_type_id);

CREATE TABLE asset.products (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    asset_class_id SMALLINT NOT NULL REFERENCES asset.asset_classes(id) ON DELETE RESTRICT,
    code VARCHAR(32) NOT NULL,
    name VARCHAR(200) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT products_code_format CHECK (code ~ '^[A-Za-z0-9_.\/-]+$'),
    CONSTRAINT products_name_nonempty CHECK (length(btrim(name)) > 0)
);
CREATE UNIQUE INDEX products_code_uq ON asset.products (upper(code));
CREATE INDEX products_asset_class_idx ON asset.products (asset_class_id);

-- A futures row must reference a product classified under FUTURE. This cross-table
-- business invariant is validated in Asset application code + integration tests.
CREATE TABLE asset.futures (
    product_id UUID PRIMARY KEY REFERENCES asset.products(id) ON DELETE RESTRICT,
    face_value NUMERIC NOT NULL,
    contract_multiplier NUMERIC NOT NULL DEFAULT 1,
    settlement_method VARCHAR(32) NOT NULL,
    settlement_description TEXT,
    CONSTRAINT futures_face_value_pos CHECK (face_value > 0),
    CONSTRAINT futures_multiplier_pos CHECK (contract_multiplier > 0),
    CONSTRAINT futures_settlement_method_nonempty CHECK (length(btrim(settlement_method)) > 0)
);

CREATE TABLE asset.instruments (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    product_id UUID NOT NULL REFERENCES asset.products(id) ON DELETE RESTRICT,
    code VARCHAR(128) NOT NULL,
    maturity_date DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT instruments_code_trimmed CHECK (length(btrim(code)) > 0 AND code = btrim(code))
);
CREATE UNIQUE INDEX instruments_code_uq ON asset.instruments (upper(code));
CREATE INDEX instruments_product_idx ON asset.instruments (product_id);
-- Whether maturity_date is required depends on the product's instrument type;
-- enforce via Asset domain validation, not a CHECK across separate tables.

-- LEDGER: one immutable entry per trade or cash movement (OQ-24), never edited; a delete removes
-- the row (OQ-32).
-- Order (entry_date, entry_time, seq) across both types; `seq` is one identity shared by both (OQ-13).
-- A trade's cash effect is not stored: it is -signed_quantity * execution_pu, computed on read.
-- On the maturity date (d = 0) the PU is typed and execution_rate is stored as 0 (OQ-1).
CREATE TABLE ledger.entries (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    type VARCHAR(8) NOT NULL,
    entry_date DATE NOT NULL,
    entry_time TIME NOT NULL,          -- Sao Paulo local time
    seq BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE NOT NULL,
    asset_id UUID REFERENCES asset.instruments(id) ON DELETE RESTRICT,   -- TRADE only
    signed_quantity INTEGER,                                             -- TRADE only
    execution_pu NUMERIC,                                                -- TRADE only
    execution_rate NUMERIC,                                              -- TRADE only
    input_kind VARCHAR(8),                                               -- TRADE only
    cash_amount NUMERIC(20,2),         -- CASH only: positive = deposit (aporte), negative = withdrawal
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT entries_type_check CHECK (type IN ('TRADE','CASH')),
    CONSTRAINT entries_trade_shape CHECK (type <> 'TRADE' OR (
        asset_id IS NOT NULL AND signed_quantity IS NOT NULL AND signed_quantity <> 0
        AND execution_pu IS NOT NULL AND execution_pu > 0
        AND execution_rate IS NOT NULL AND execution_rate > -1
        AND input_kind IS NOT NULL AND input_kind IN ('PU','RATE') AND cash_amount IS NULL)),
    CONSTRAINT entries_cash_shape CHECK (type <> 'CASH' OR (
        cash_amount IS NOT NULL AND cash_amount <> 0
        AND asset_id IS NULL AND signed_quantity IS NULL AND execution_pu IS NULL
        AND execution_rate IS NULL AND input_kind IS NULL))
);
CREATE INDEX entries_ordered_idx ON ledger.entries (entry_date, entry_time, seq);
CREATE INDEX entries_trade_asset_date_idx ON ledger.entries (asset_id, entry_date, seq) WHERE type = 'TRADE';

-- PRICES: one observation per asset, date and source (OQ-25). A correction updates the row in place;
-- a removal deletes it. MANUAL > B3 is read policy, not an overwrite of the lower-priority source.
CREATE TABLE prices.reference_prices (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    asset_id UUID NOT NULL REFERENCES asset.instruments(id) ON DELETE RESTRICT,
    reference_date DATE NOT NULL,
    source VARCHAR(16) NOT NULL,
    input_kind VARCHAR(8) NOT NULL,
    pu NUMERIC NOT NULL,
    rate NUMERIC,
    calculation_method VARCHAR(32),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT reference_prices_source_check CHECK (source IN ('MANUAL','B3')),
    CONSTRAINT reference_prices_input_kind_check CHECK (input_kind IN ('PU','RATE')),
    CONSTRAINT reference_prices_pu_positive CHECK (pu > 0),
    CONSTRAINT reference_prices_rate_valid CHECK (rate IS NULL OR rate > -1),
    CONSTRAINT reference_prices_rate_present_if_entered CHECK (input_kind <> 'RATE' OR rate IS NOT NULL),
    CONSTRAINT reference_prices_one_per_source UNIQUE (asset_id, reference_date, source)
);
CREATE INDEX reference_prices_date_idx ON prices.reference_prices (reference_date, asset_id);

-- PROCESSING: user-requested runs, singleton coordination, per-date chain status, issues.
-- A run processes one scope (OQ-21) and publishes each date in its own transaction (OQ-23).
CREATE TABLE processing.requests (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    scope VARCHAR(16) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'QUEUED',
    progress_date DATE,                -- the last date the run committed; recovery resumes after it
    error_code VARCHAR(64),
    error_message TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    dispatched_at TIMESTAMPTZ,
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    cancel_requested_at TIMESTAMPTZ,
    claim_token UUID,
    lease_expires_at TIMESTAMPTZ,
    attempt_count INTEGER NOT NULL DEFAULT 0,
    failed_date DATE,                  -- the run's first failure (OQ-40)
    failed_chain VARCHAR(16),          -- CASH | POSITIONS; NULL with failed_date: a failure of no chain
    CONSTRAINT requests_scope_check CHECK (scope IN ('CASH','POSITIONS','ALL')),
    CONSTRAINT requests_dates_ordered CHECK (start_date <= end_date),
    CONSTRAINT requests_status_check CHECK (status IN ('QUEUED','DISPATCHED','RUNNING','CANCELLING','COMPLETED','COMPLETED_WITH_ISSUES','CANCELLED','FAILED')),
    CONSTRAINT requests_progress_in_range CHECK (progress_date IS NULL OR progress_date BETWEEN start_date AND end_date),
    CONSTRAINT requests_attempts_nonnegative CHECK (attempt_count >= 0),
    CONSTRAINT requests_failed_chain_check CHECK (failed_chain IS NULL OR failed_chain IN ('CASH','POSITIONS')),
    CONSTRAINT requests_failed_chain_needs_date CHECK (failed_chain IS NULL OR failed_date IS NOT NULL),
    CONSTRAINT requests_failed_date_in_range CHECK (failed_date IS NULL OR failed_date BETWEEN start_date AND end_date)
);
CREATE INDEX requests_queue_idx ON processing.requests (created_at, id) WHERE status = 'QUEUED';
CREATE INDEX requests_recent_idx ON processing.requests (created_at DESC);
CREATE INDEX requests_active_idx ON processing.requests (status) WHERE status IN ('DISPATCHED','RUNNING','CANCELLING');

CREATE TABLE processing.calculation_state (
    singleton BOOLEAN PRIMARY KEY DEFAULT TRUE CHECK (singleton),
    active_request_id UUID REFERENCES processing.requests(id) ON DELETE SET NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
INSERT INTO processing.calculation_state(singleton) VALUES (TRUE);

-- The current status of each chain on each date (OQ-23, OQ-31). A NULL status, or no row, is "not
-- processed". Only a run writes it: RUNNING, then PROCESSED, PROCESSED_WITH_ISSUES or FAILED; a
-- write in Ledger or Prices changes nothing here (no staleness, OQ-31). *_processed_at is when a
-- run last committed that chain for the date ("Processado em ..."). A RUNNING chain keeps its previous
-- status in *_previous, put back if the run ends without committing that date (OQ-26).
CREATE TABLE processing.date_status (
    date DATE PRIMARY KEY,
    portfolio VARCHAR(32),
    cash VARCHAR(32),
    portfolio_previous VARCHAR(32),    -- the status before RUNNING, put back if the run ends without this date (OQ-26)
    cash_previous VARCHAR(32),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    portfolio_processed_at TIMESTAMPTZ,
    cash_processed_at TIMESTAMPTZ,
    CONSTRAINT date_status_portfolio_check CHECK (portfolio IS NULL OR portfolio IN ('PROCESSED','PROCESSED_WITH_ISSUES','RUNNING','FAILED')),
    CONSTRAINT date_status_cash_check CHECK (cash IS NULL OR cash IN ('PROCESSED','PROCESSED_WITH_ISSUES','RUNNING','FAILED')),
    CONSTRAINT date_status_portfolio_previous_check CHECK (portfolio_previous IS NULL OR (portfolio = 'RUNNING' AND portfolio_previous IN ('PROCESSED','PROCESSED_WITH_ISSUES','FAILED'))),
    CONSTRAINT date_status_cash_previous_check CHECK (cash_previous IS NULL OR (cash = 'RUNNING' AND cash_previous IN ('PROCESSED','PROCESSED_WITH_ISSUES','FAILED'))),
    CONSTRAINT date_status_not_empty CHECK (portfolio IS NOT NULL OR cash IS NOT NULL)
);

CREATE TABLE processing.issues (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    request_id UUID NOT NULL REFERENCES processing.requests(id) ON DELETE CASCADE,
    asset_id UUID REFERENCES asset.instruments(id) ON DELETE RESTRICT,
    affected_date DATE NOT NULL,
    required_price_date DATE,
    issue_type VARCHAR(64) NOT NULL,   -- MISSING_REFERENCE_PRICE | EXPIRED_OPEN_POSITION (OQ-31)
    message TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT issues_type_nonempty CHECK (length(btrim(issue_type)) > 0)
);
CREATE UNIQUE INDEX issues_unique_per_request_idx ON processing.issues (request_id, asset_id, affected_date, required_price_date, issue_type) NULLS NOT DISTINCT;
CREATE INDEX issues_by_date_idx ON processing.issues (affected_date, issue_type);

-- PORTFOLIO: one portfolio, no portfolio_id; published data only.
CREATE TABLE portfolio.positions (
    asset_id UUID NOT NULL REFERENCES asset.instruments(id) ON DELETE RESTRICT,
    position_date DATE NOT NULL,
    quantity INTEGER NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY(asset_id, position_date)
);
CREATE INDEX positions_date_idx ON portfolio.positions (position_date, asset_id);

-- The reference PU, rate and source of a date live only in prices.reference_prices; a published
-- day keeps its computed financial_total and P&L until the user processes it again (OQ-30, OQ-31).
CREATE TABLE portfolio.position_metrics (
    asset_id UUID NOT NULL,
    metric_date DATE NOT NULL,
    average_entry_pu NUMERIC,
    average_entry_rate NUMERIC,
    financial_total NUMERIC,
    position_pnl NUMERIC,
    trades_pnl NUMERIC,
    daily_pnl NUMERIC,
    valuation_status VARCHAR(16) NOT NULL,
    pnl_status VARCHAR(16) NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY(asset_id, metric_date),
    FOREIGN KEY (asset_id, metric_date) REFERENCES portfolio.positions(asset_id, position_date) ON DELETE CASCADE,
    CONSTRAINT position_metrics_average_pu_positive CHECK (average_entry_pu IS NULL OR average_entry_pu > 0),
    CONSTRAINT position_metrics_average_rate_valid CHECK (average_entry_rate IS NULL OR average_entry_rate > -1),
    CONSTRAINT position_metrics_valuation_status CHECK (valuation_status IN ('COMPLETE','MISSING','NOT_REQUIRED')),
    CONSTRAINT position_metrics_pnl_status CHECK (pnl_status IN ('COMPLETE','MISSING')),
    CONSTRAINT position_metrics_daily_pnl_parts CHECK (daily_pnl IS NULL OR (position_pnl IS NOT NULL AND trades_pnl IS NOT NULL AND daily_pnl = position_pnl + trades_pnl)),
    CONSTRAINT position_metrics_valuation_missing_null CHECK (valuation_status <> 'MISSING' OR financial_total IS NULL)
);
CREATE INDEX position_metrics_date_idx ON portfolio.position_metrics (metric_date, asset_id);

-- aum is kept but unused (NULL): AUM = cash_balances.cash_balance + positions_market_value of the
-- same date is computed on read, when both chains of the date are processed (OQ-21, OQ-38).
CREATE TABLE portfolio.portfolio_metrics (
    metric_date DATE PRIMARY KEY,
    positions_market_value NUMERIC,
    aum NUMERIC,
    position_pnl NUMERIC,
    trades_pnl NUMERIC,
    daily_pnl NUMERIC,
    cumulative_pnl NUMERIC,
    valuation_status VARCHAR(16) NOT NULL,
    pnl_status VARCHAR(16) NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT portfolio_metrics_valuation_status CHECK (valuation_status IN ('COMPLETE','MISSING')),
    CONSTRAINT portfolio_metrics_pnl_status CHECK (pnl_status IN ('COMPLETE','MISSING')),
    CONSTRAINT portfolio_metrics_aum_needs_market_value CHECK (aum IS NULL OR positions_market_value IS NOT NULL),
    CONSTRAINT portfolio_metrics_daily_pnl_parts CHECK (daily_pnl IS NULL OR (position_pnl IS NOT NULL AND trades_pnl IS NOT NULL AND daily_pnl = position_pnl + trades_pnl)),
    CONSTRAINT portfolio_metrics_missing_valuation_null CHECK (valuation_status <> 'MISSING' OR (positions_market_value IS NULL AND aum IS NULL))
);

-- The cash chain (OQ-21), one row per processed calendar day:
--   cash_balance[D] = cash_balance[D-1] + trades_cash_flow[D] + deposits[D] - withdrawals[D]
--   trades_cash_flow[D] = -sum(signed_quantity * execution_pu) over the day's trades
-- Owned by Portfolio, like the other published tables (OQ-8).
CREATE TABLE portfolio.cash_balances (
    balance_date DATE PRIMARY KEY,
    cash_balance NUMERIC NOT NULL,
    trades_cash_flow NUMERIC NOT NULL,
    deposits NUMERIC NOT NULL,
    withdrawals NUMERIC NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT cash_balances_movements_nonnegative CHECK (deposits >= 0 AND withdrawals >= 0)
);
-- PLATFORM: durable command/event delivery and consumer idempotency.
CREATE TABLE platform.outbox_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id UUID NOT NULL UNIQUE DEFAULT gen_random_uuid(),
    message_type VARCHAR(128) NOT NULL,
    schema_version SMALLINT NOT NULL DEFAULT 1 CHECK (schema_version > 0),
    payload JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    published_at TIMESTAMPTZ,
    publish_attempts INTEGER NOT NULL DEFAULT 0 CHECK (publish_attempts >= 0),
    last_error TEXT
);
CREATE INDEX outbox_unpublished_idx ON platform.outbox_messages (id) WHERE published_at IS NULL;

CREATE TABLE platform.inbox_messages (
    consumer_name VARCHAR(128) NOT NULL,
    message_id UUID NOT NULL,
    processed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY(consumer_name, message_id)
);
COMMIT;
